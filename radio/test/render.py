class Screen:
    def __init__(self):
        self.px = [[0] * W for _ in range(H)]

    def set(self, x, y, on):
        if 0 <= x < W and 0 <= y < H:
            self.px[y][x] = 1 if on else 0

    def get(self, x, y):
        return self.px[y][x] if 0 <= x < W and 0 <= y < H else 0

    def line(self, x1, y1, x2, y2, pattern, flags):
        on = not flags & ERASE
        dx, dy = abs(x2 - x1), -abs(y2 - y1)
        sx, sy = (1 if x1 < x2 else -1), (1 if y1 < y2 else -1)
        err, i = dx + dy, 0
        while True:
            if pattern == 0 or i % 2 == 0:  # 0 = SOLID, else DOTTED
                self.set(x1, y1, on)
            if x1 == x2 and y1 == y2:
                break
            e2 = 2 * err
            if e2 >= dy:
                err += dy
                x1 += sx
            if e2 <= dx:
                err += dx
                y1 += sy
            i += 1

    def rect(self, x, y, w, h, flags):
        for i in range(w):
            self.set(x + i, y, not flags & ERASE)
            self.set(x + i, y + h - 1, not flags & ERASE)
        for j in range(h):
            self.set(x, y + j, not flags & ERASE)
            self.set(x + w - 1, y + j, not flags & ERASE)

    def fill(self, x, y, w, h, flags):
        for j in range(h):
            for i in range(w):
                self.set(x + i, y + j, not flags & ERASE)

    def text(self, x, y, flags, s):
        font, adv_extra, rows = (SML, 1, 5) if flags & SMLSIZE else (STD, 1, 7)
        width = sum(len(font.get(c, font[' '])[0]) + adv_extra for c in s)
        if flags & RIGHT:
            x -= width
        if flags & INVERS:
            self.fill(x - 1, y - 1, width + 1, rows + 2, 0)
        cx = x
        for c in s:
            g = font.get(c)
            if g is None:
                g = font.get(c.upper(), ["111"] * rows)
            for j, row in enumerate(g):
                for i, b in enumerate(row):
                    if b == '1':
                        self.set(cx + i, y + j, not flags & INVERS)
            cx += len(g[0]) + adv_extra


def render(log, out, scale):
    s = Screen()
    for raw in open(log):
        line = raw.rstrip('\n')
        op = line[:1]
        args = line[2:].split(' ', 3) if op == 'T' else line[2:].split()
        if op == 'C':
            s = Screen()
        elif op == 'L':
            s.line(*map(int, args[:6]))
        elif op == 'R':
            s.rect(*map(int, args[:5]))
        elif op == 'F':
            s.fill(*map(int, args[:5]))
        elif op == 'P':
            s.set(int(args[0]), int(args[1]), not int(args[2]) & ERASE)
        elif op == 'T':
            s.text(int(args[0]), int(args[1]), int(args[2]), args[3] if len(args) > 3 else '')
    # Pocket-ish LCD colours: dark pixels on a pale backlight.
    img = Image.new('RGB', (W * scale + 2 * scale, H * scale + 2 * scale), (190, 205, 190))
    for y in range(H):
        for x in range(W):
            if s.px[y][x]:
                for j in range(scale):
                    for i in range(scale):
                        img.putpixel(((x + 1) * scale + i, (y + 1) * scale + j), (20, 30, 25))
    img.save(out)


def sheet(pngs, out, cols=2, gap=8):
    ims = [Image.open(p) for p in pngs]
    w, h = ims[0].size
    rows = (len(ims) + cols - 1) // cols
    img = Image.new('RGB', (cols * w + (cols - 1) * gap, rows * h + (rows - 1) * gap), (255, 255, 255))
    for i, im in enumerate(ims):
        img.paste(im, ((i % cols) * (w + gap), (i // cols) * (h + gap)))
    img.save(out)


